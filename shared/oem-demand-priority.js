export function normalizeDemandText(value) {
  return String(value || "")
    .replace(/ı/g, "i")
    .replace(/İ/g, "i")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
}

export function compactDemandText(value) {
  return normalizeDemandText(value).replace(/[^a-z0-9]+/g, "");
}

export function matchOemDemandGroup(productOrText) {
  const raw = typeof productOrText === "string"
    ? productOrText
    : [
        productOrText?.name,
        productOrText?.sku,
        productOrText?.oem,
        productOrText?.desc,
        productOrText?.cat,
        ...(Array.isArray(productOrText?.compat) ? productOrText.compat : []),
      ].filter(Boolean).join(" ");
  const haystack = compactDemandText(raw);
  if (!haystack) return null;
  return OEM_DEMAND_GROUPS.find(group =>
    group.codes.some(code => haystack.includes(compactDemandText(code)))
  ) || null;
}

export function prioritySeoProductName(product, max = 140) {
  const group = matchOemDemandGroup(product);
  if (!group) return "";
  const sku = String(product?.sku || "").trim();
  const pieces = [group.label, sku && !compactDemandText(group.label).includes(compactDemandText(sku)) ? sku : ""]
    .filter(Boolean);
  const text = pieces.join(" ").replace(/\s+/g, " ").trim();
  if (text.length <= max) return text;
  return text.slice(0, Math.max(24, max - 1)).replace(/\s+\S*$/, "").trim();
}

export function demandLandingUrl(site, group) {
  const root = String(site || "").replace(/\/+$/g, "");
  return group?.slug ? `${root}/${group.slug}` : root;
}
