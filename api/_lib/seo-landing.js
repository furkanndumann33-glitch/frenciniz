function slugify(value) {
  return normalize(value)
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function buildLandingPage(vehicle, partKey) {
  const part = PART_LANDING_GROUPS[partKey];
  const heading = `${vehicle.label} ${part.label}`;
  const priority = Math.min(0.9, Number(vehicle.priority || 0.78) + Number(part.priorityBoost || 0)).toFixed(2);
  return {
    slug: `${vehicle.key}-${slugify(partKey)}`,
    heading,
    title: `${heading} | Fiyat ve Stok | Frenciniz`,
    description: `${vehicle.label} uyumlu ${part.part} ürünleri. OEM/parça kodu ile uyumluluk teyidi, stok ve fiyat kontrolü, aynı gün kargo ve WhatsApp hızlı teklif.`,
    cats: part.cats,
    terms: [...new Set([...(vehicle.terms || []), ...(part.terms || [])])],
    primaryTerm: vehicle.primaryTerm || vehicle.label,
    part: part.part,
    priority,
  };
}

function registerGeneratedLandingPages() {
  const seen = new Set(LANDING_PAGES.map(page => page.slug));

  for (const vehicle of VEHICLE_LANDING_GROUPS) {
    for (const partKey of vehicle.parts) {
      if (!PART_LANDING_GROUPS[partKey]) continue;
      const page = buildLandingPage(vehicle, partKey);
      if (seen.has(page.slug)) continue;
      LANDING_PAGES.push(page);
      seen.add(page.slug);
    }
  }
}

registerGeneratedLandingPages();

function applyStrictLandingDescriptions() {
  for (const page of LANDING_PAGES) {
    page.description = `${page.heading} icin ${page.part || "fren aksami"} urunlerinde stok ve fiyat secenekleri. OEM/parca kodu, eski parca fotografi veya sase ile uyumluluk teyidi, ayni gun kargo ve WhatsApp teklif.`;
  }
}

applyStrictLandingDescriptions();

export function getLandingBySlug(slug) {
  return LANDING_PAGES.find(page => page.slug === slug);
}

export function xmlEscape(s) {
  return String(s || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

export function htmlEscape(s) {
  return xmlEscape(s);
}

function normalize(s) {
  return String(s || "")
    .toLocaleLowerCase("tr-TR")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/ı/g, "i")
    .replace(/ğ/g, "g")
    .replace(/ü/g, "u")
    .replace(/ş/g, "s")
    .replace(/ö/g, "o")
    .replace(/ç/g, "c");
}

export function productText(product) {
  return normalize([
    product?.name,
    product?.sku,
    product?.oem,
    product?.cat,
    product?.brand,
    ...(product?.compat || []),
    ...(product?.veh || []),
  ].filter(Boolean).join(" "));
}

function hasRealImage(product) {
  return Boolean(product?.img && !String(product.img).includes("placehold"));
}

export function absoluteImage(product) {
  const fallback = `${SITE}/img/site/frenciniz-logo-real-og.jpg`;
  const raw = hasRealImage(product) ? String(product.img) : fallback;
  if (raw.startsWith("http")) return raw;
  return `${SITE}${raw.startsWith("/") ? "" : "/"}${raw}`;
}

export function categoryName(categories, id) {
  return categories.find(category => category.id === id)?.name || id || "Fren Aksamı";
}

export function scoreProductForLanding(product, page) {
  const text = productText(product);
  let score = 0;
  if (page.cats?.includes(product.cat)) score += 80;
  for (const term of page.terms || []) {
    if (text.includes(normalize(term))) score += 18;
  }
  if (page.primaryTerm && text.includes(normalize(page.primaryTerm))) score += 25;
  if (product.stock > 0) score += Math.min(15, Math.ceil(Number(product.stock) / 50));
  if (hasRealImage(product)) score += 8;
  if (product.oem) score += 4;
  return score;
}

export function filterProductsForLanding(products, page, limit = 24) {
  const scored = products
    .map(product => ({ product, score: scoreProductForLanding(product, page) }))
    .filter(row => row.score >= 80)
    .sort((a, b) => b.score - a.score || Number(b.product.stock || 0) - Number(a.product.stock || 0));

  const exact = scored.map(row => row.product);
  if (exact.length >= Math.min(6, limit)) return exact.slice(0, limit);

  const related = products
    .map(product => ({ product, score: scoreProductForLanding(product, { ...page, terms: [] }) }))
    .filter(row => row.score >= 80 && !exact.some(item => item.id === row.product.id))
    .sort((a, b) => b.score - a.score || Number(b.product.stock || 0) - Number(a.product.stock || 0))
    .map(row => row.product);

  return [...exact, ...related].slice(0, limit);
}

